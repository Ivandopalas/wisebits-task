import { randomBytes } from 'node:crypto';

/** A minimal EBML header with DocType "webm": enough for signature detection. */
const WEBM_HEADER = Buffer.from([
  0x1a, 0x45, 0xdf, 0xa3, 0x9f, 0x42, 0x86, 0x81, 0x01, 0x42, 0xf7, 0x81, 0x01, 0x42, 0xf2, 0x81,
  0x04, 0x42, 0xf3, 0x81, 0x08, 0x42, 0x82, 0x84, 0x77, 0x65, 0x62, 0x6d, 0x42, 0x87, 0x81, 0x04,
  0x42, 0x85, 0x81, 0x02,
]);

/** An ISO BMFF `ftyp` box with the "isom" brand, as Safari's MediaRecorder writes. */
const MP4_HEADER = Buffer.from([
  0x00, 0x00, 0x00, 0x18, 0x66, 0x74, 0x79, 0x70, 0x69, 0x73, 0x6f, 0x6d, 0x00, 0x00, 0x02, 0x00,
  0x69, 0x73, 0x6f, 0x6d, 0x6d, 0x70, 0x34, 0x32,
]);

const PNG_HEADER = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

const withBody = (header: Buffer, size: number) =>
  Buffer.concat([header, randomBytes(Math.max(size - header.length, 0))]);

export const fakeWebm = (size = 64 * 1024) => withBody(WEBM_HEADER, size);
export const fakeMp4 = (size = 64 * 1024) => withBody(MP4_HEADER, size);
export const fakePng = (size = 1024) => withBody(PNG_HEADER, size);
